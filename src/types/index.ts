import type { TechnologyId } from '../data/technologies';

export type Language = 'es' | 'en';

export type Localized<T = string> = Record<Language, T>;

export type ProjectCategory = 'games' | 'web' | 'software';

/** Each team member has a planet of their own, designed from the reference they chose. */
export type MemberPlanet = 'mariana' | 'dilanov' | 'fredev' | 'aigen';

/** A member's planet, or Mariana and DilanOv's pair (`couple`), which stands for an area. */
export type PlanetKind = MemberPlanet | 'couple';

/** `in-use` is for private tools already working for someone, with nothing public to open. */
export type ProjectStatus = 'live' | 'development' | 'in-use';

export interface ProjectScreenshot {
  /** File name (without extension) generated by `npm run images` in public/projects. */
  file: string;
  alt: Localized;
  /** CSS object-position used when the card crops the screenshot. Defaults to center. */
  focus?: string;
}

export interface Project {
  id: string;
  name: string;
  category: ProjectCategory;
  status: ProjectStatus;
  /** Display order inside its area. Every project has the same visual hierarchy. */
  order: number;
  tagline: Localized;
  description: Localized;
  features: Localized<readonly string[]>;
  /** Up to four technologies shown on the card. */
  cardTechnologies: readonly TechnologyId[];
  /** Full list shown in the detail view. */
  technologies: readonly TechnologyId[];
  /**
   * Public destinations only. The site never links to a project's source code, except
   * `github` for the studio's own public tools that are distributed from their repository.
   */
  links: {
    demo?: string;
    github?: string;
  };
  /** Cover shown on the card and first in the detail view. */
  screenshot: ProjectScreenshot;
  /**
   * Every screenshot of the detail view, in order, when there is more than one. It includes the
   * cover (same `file`), and the detail view opens on it.
   */
  gallery?: readonly ProjectScreenshot[];
}
